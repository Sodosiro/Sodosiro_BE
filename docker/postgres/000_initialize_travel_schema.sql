ALTER TABLE review
    ADD COLUMN IF NOT EXISTS visit_type      VARCHAR(20)  NOT NULL DEFAULT 'GENERAL',
    ADD COLUMN IF NOT EXISTS gps_verified_at TIMESTAMP(6);

-- 기존 환경: rating SMALLINT → NUMERIC(3,1) 타입 변환
DO $$
DECLARE v_constraint_name TEXT;
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'review' AND column_name = 'rating'
          AND data_type = 'smallint'
    ) THEN
        -- inline CHECK (rating BETWEEN 1 AND 5) 를 constraint 이름으로 찾아 제거
        SELECT con.conname INTO v_constraint_name
        FROM pg_constraint con
        JOIN pg_class rel ON rel.oid = con.conrelid
        WHERE rel.relname = 'review'
          AND con.contype = 'c'
          AND pg_get_constraintdef(con.oid) LIKE '%rating%';

        IF v_constraint_name IS NOT NULL THEN
            EXECUTE 'ALTER TABLE review DROP CONSTRAINT ' || quote_ident(v_constraint_name);
        END IF;

        ALTER TABLE review ALTER COLUMN rating TYPE NUMERIC(3,1) USING rating::NUMERIC(3,1);
    END IF;
END $$;

-- CHECK constraint (IF NOT EXISTS 방어)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_review_visit_type') THEN
        ALTER TABLE review ADD CONSTRAINT chk_review_visit_type
            CHECK (visit_type IN ('GENERAL', 'GPS_VERIFIED'));
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_review_rating') THEN
        ALTER TABLE review ADD CONSTRAINT chk_review_rating
            CHECK (rating BETWEEN 0.1 AND 5.0);
    END IF;
END $$;

-- 소프트 딜리트 정합성: (content_id, user_id) 전체 유니크 → 활성 리뷰(is_deleted=false)만 유니크
-- 삭제 후 재작성 시 남아있는 soft-deleted 행 때문에 발생하던 uk_review_user_spot 위반 방지
ALTER TABLE review DROP CONSTRAINT IF EXISTS uk_review_user_spot;

CREATE UNIQUE INDEX IF NOT EXISTS uk_review_user_spot_active
    ON review (content_id, user_id) WHERE is_deleted = FALSE;

-- users FK: JPA가 앱 기동 시 users 테이블을 생성하므로 존재할 때만 추가
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'users'
    ) AND NOT EXISTS (
        SELECT 1 FROM information_schema.table_constraints
        WHERE table_name = 'review' AND constraint_name = 'fk_review_user'
    ) THEN
        EXECUTE 'ALTER TABLE review ADD CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE';
    END IF;
END $$;

