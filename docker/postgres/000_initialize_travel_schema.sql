-- 기존 환경: avg_rating NUMERIC(3,2) → NUMERIC(3,1) 타입 변환
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'tourist_spot' AND column_name = 'avg_rating'
          AND numeric_scale = 2
    ) THEN
        ALTER TABLE tourist_spot ALTER COLUMN avg_rating TYPE NUMERIC(3,1) USING avg_rating::NUMERIC(3,1);
    END IF;
END $$;

